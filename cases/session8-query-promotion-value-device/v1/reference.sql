WITH eligible AS (
SELECT ORDER_ID,DEVICE,TOTAL_AMOUNT-SHIPPING_AMOUNT AS merchandise_amount
FROM BOOTCAMP_DB.NOVAMART.ORDERS
WHERE STATUS='completed' AND PROMO_ID IS NOT NULL
AND ORDER_DATE>=DATE '2024-11-01' AND ORDER_DATE<DATE '2024-12-01'
)
SELECT DEVICE AS "segment",ROUND(SUM(merchandise_amount),2) AS "value"
FROM eligible GROUP BY DEVICE ORDER BY DEVICE
