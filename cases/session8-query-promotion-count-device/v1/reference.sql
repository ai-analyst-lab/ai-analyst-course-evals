SELECT DEVICE AS "segment",
SUM(CASE WHEN STATUS='completed' AND PROMO_ID IS NOT NULL THEN 1 ELSE 0 END) AS "value"
FROM BOOTCAMP_DB.NOVAMART.ORDERS
WHERE ORDER_DATE>=DATE '2024-11-01' AND ORDER_DATE<DATE '2024-12-01'
GROUP BY DEVICE
HAVING SUM(CASE WHEN STATUS='completed' AND PROMO_ID IS NOT NULL THEN 1 ELSE 0 END)>0
ORDER BY DEVICE
