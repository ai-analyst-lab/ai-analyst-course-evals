SELECT TO_CHAR(s.SESSION_DATE, 'YYYY-MM') AS "segment",
  ROUND(100.0 * COUNT_IF(EXISTS (
    SELECT 1 FROM BOOTCAMP_DB.NOVAMART.EVENTS e
    WHERE e.SESSION_ID = s.SESSION_ID AND e.EVENT_TYPE = 'purchase_complete'
  )) / NULLIF(COUNT(*), 0), 4) AS "value"
FROM BOOTCAMP_DB.NOVAMART.SESSIONS s
WHERE s.SESSION_DATE >= DATE '2024-10-01' AND s.SESSION_DATE < DATE '2025-01-01'
GROUP BY 1 ORDER BY 1
