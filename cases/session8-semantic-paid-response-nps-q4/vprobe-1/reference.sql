WITH eligible AS (
 SELECT n.RESPONSE_ID,n.RESPONSE_DATE,n.SCORE
 FROM BOOTCAMP_DB.NOVAMART.NPS_RESPONSES n
 WHERE n.RESPONSE_DATE>=DATE '2024-10-01' AND n.RESPONSE_DATE<DATE '2025-01-01'
 AND EXISTS (
 SELECT 1 FROM BOOTCAMP_DB.NOVAMART.MEMBERSHIPS t
 JOIN BOOTCAMP_DB.NOVAMART.MEMBERSHIPS p ON p.USER_ID=t.USER_ID
 AND p.PLAN_TYPE IN ('plus_monthly','plus_annual')
 WHERE t.USER_ID=n.USER_ID AND t.PLAN_TYPE='plus_trial' AND t.STATUS='converted'
 AND CAST(n.RESPONSE_DATE AS TIMESTAMP_NTZ)>=t.ENDED_AT
 AND (p.ENDED_AT IS NULL OR CAST(n.RESPONSE_DATE AS TIMESTAMP_NTZ)<p.ENDED_AT)))
SELECT '2024-Q4' AS "segment", ROUND(100.0*SUM(CASE WHEN SCORE>=9 THEN 1 WHEN SCORE<=6 THEN -1 ELSE 0 END)/NULLIF(COUNT(*),0),4) AS "value" FROM eligible
