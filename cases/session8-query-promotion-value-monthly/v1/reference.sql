WITH per_day AS (
SELECT ORDER_DATE,SUM(TOTAL_AMOUNT-SHIPPING_AMOUNT) AS amount
FROM BOOTCAMP_DB.NOVAMART.ORDERS
WHERE STATUS='completed' AND PROMO_ID IS NOT NULL
AND ORDER_DATE>=DATE '2024-10-01' AND ORDER_DATE<DATE '2025-01-01'
GROUP BY ORDER_DATE
)
SELECT TO_CHAR(DATE_TRUNC('month',ORDER_DATE),'YYYY-MM') AS "segment",
ROUND(SUM(amount),2) AS "value" FROM per_day
GROUP BY DATE_TRUNC('month',ORDER_DATE) ORDER BY "segment"
