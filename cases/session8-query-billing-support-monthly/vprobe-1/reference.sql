SELECT TO_CHAR(CREATED_DATE,'YYYY-MM') AS "segment", COUNT(DISTINCT TICKET_ID) AS "value"
FROM BOOTCAMP_DB.NOVAMART.SUPPORT_TICKETS WHERE CREATED_DATE >= DATE '2024-10-01' AND CREATED_DATE < DATE '2025-01-01'
AND CATEGORY IN ('payment_issue','membership_issue') GROUP BY TO_CHAR(CREATED_DATE,'YYYY-MM') ORDER BY "segment"
